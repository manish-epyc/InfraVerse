/** Builds an edge with a derived id. `source` depends on / calls `target`. */
function edge(
  source: string,
  target: string,
  trafficRps: number,
  latencyMs: number,
  errorRatePercentage: number,
): ServiceEdge {
  return {
    id: `${source}__${target}`,
    source,
    target,
    trafficRps,
    latencyMs,
    errorRatePercentage,
  };
}

