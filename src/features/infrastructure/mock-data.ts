/** Builds an event-log entry with a derived id. */
function log(
  timestamp: string,
  serviceId: string,
  type: EventLogType,
  message: string,
): EventLog {
  return { id: `evt__${serviceId}__${timestamp}`, timestamp, serviceId, type, message };
}

